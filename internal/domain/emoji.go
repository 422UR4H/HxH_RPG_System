package domain

// emojiRanges lista as faixas de code points tratadas como emoji (inclusivas).
// A MESMA tabela existe no front, em System_X_System_React/src/constants/fieldLimits.ts;
// mantenha as duas idênticas. ZWJ (U+200D) fica de fora de propósito: é usado em
// escritas como árabe e devanágari, e toda sequência com ZWJ já tem um pictograma nas faixas.
var emojiRanges = [][2]rune{
	{0x00A9, 0x00A9}, {0x00AE, 0x00AE}, {0x203C, 0x203C}, {0x2049, 0x2049},
	{0x2122, 0x2122}, {0x2139, 0x2139}, {0x2194, 0x2199}, {0x21A9, 0x21AA},
	{0x231A, 0x231B}, {0x2328, 0x2328}, {0x23CF, 0x23CF}, {0x23E9, 0x23F3},
	{0x23F8, 0x23FA}, {0x24C2, 0x24C2}, {0x25AA, 0x25AB}, {0x25B6, 0x25B6},
	{0x25C0, 0x25C0}, {0x25FB, 0x25FE}, {0x2600, 0x27BF}, {0x2934, 0x2935},
	{0x2B05, 0x2B07}, {0x2B1B, 0x2B1C}, {0x2B50, 0x2B50}, {0x2B55, 0x2B55},
	{0x3030, 0x3030}, {0x303D, 0x303D}, {0x3297, 0x3297}, {0x3299, 0x3299},
	{0xFE0F, 0xFE0F}, {0x20E3, 0x20E3}, {0x1F000, 0x1FAFF}, {0xE0020, 0xE007F},
}

// ContainsEmoji informa se s tem algum code point nas faixas de emoji.
func ContainsEmoji(s string) bool {
	for _, r := range s {
		for _, rg := range emojiRanges {
			if r >= rg[0] && r <= rg[1] {
				return true
			}
		}
	}
	return false
}
